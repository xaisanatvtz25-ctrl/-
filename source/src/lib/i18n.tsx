const DICTS: Record<Lang, Record<Key, string>> = { lo, th };

interface I18nValue {
    lang: Lang;
    setLang: (lang: Lang) => void;
    t: (key: Key, vars?: Record<string, string | number>) => string;
    monthName: (month: number) => string;
    weekdays: string[];
    suggestions: string[];
}

const I18nContext = createContext<I18nValue | null>(null);
const LANG_KEY = 'milako.lang';

function readLang(): Lang {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved === 'lo' || saved === 'th') {
            return saved;
        }
    } catch {
        // ignore
    }
    return 'lo';
}

export function I18nProvider({ children }: { children: ReactNode }) {
    const [lang, setLangState] = useState<Lang>(readLang);

    useEffect(() => {
        document.documentElement.lang = lang;
    }, [lang]);

    const setLang = useCallback((next: Lang) => {
        setLangState(next);
        try {
            localStorage.setItem(LANG_KEY, next);
        } catch {
            // ignore
        }
    }, []);

    const value = useMemo<I18nValue>(() => {
        const dict = DICTS[lang];
        return {
            lang,
            setLang,
            t: (key, vars) => {
                let text = dict[key] ?? lo[key] ?? key;
                if (vars) {
                    for (const [k, v] of Object.entries(vars)) {
                        text = text.split(`{${k}}`).join(String(v));
                    }
                }
                return text;
            },
            monthName: (month) => MONTHS[lang][month - 1] || String(month),
            weekdays: WEEKDAYS[lang],
            suggestions: SUGGESTIONS[lang],
        };
    }, [lang, setLang]);

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
    const ctx = useContext(I18nContext);
    if (!ctx) {
        throw new Error('useI18n must be used inside I18nProvider');
    }
    return ctx;
}

